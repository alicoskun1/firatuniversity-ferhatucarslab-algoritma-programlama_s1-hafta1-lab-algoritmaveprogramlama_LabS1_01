public class IkiIslem {
    public static void main(String[] args) {
        // İki int değişken tanımlanıyor ve değerleri değiştirilmiyor
        int a = 17;
        double b = 5;

        // Toplamı, farkı, çarpımı, bölümü ve kalanı etiketleriyle yazdırma
        System.out.println(a + " + " + b + " = " + (a + b));
        System.out.println(a + " - " + b + " = " + (a - b));
        System.out.println(a + " * " + b + " = " + (a * b));
        System.out.println(a + " / " + b + " = " + (a / b));
        System.out.println(a + " % " + b + " = " + (a % b));

       // int değeri double ile değiştirildiğinde kesin ondalıklı sonuca ulaşılıyor
         
    }
}